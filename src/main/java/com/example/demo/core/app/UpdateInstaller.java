package com.example.demo.core.app;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

/**
 * 真正把更新装上去：静默安装 → 自动重启 → 下次启动确认版本。
 *
 * <p>这里的安装包是 {@code jpackage --type exe} 产出的，静默参数是 <b>{@code /quiet}</b>
 * （不是 Inno 的 /VERYSILENT）。旧代码用了 Inno 的参数，所以「立即安装」实际上什么都没做。
 *
 * <p>流程：
 * <ol>
 *   <li>写一个 pending 标记（记下目标版本和安装包路径）；</li>
 *   <li>写一个 .cmd 助手：等 2 秒让启动器退出（否则 exe 被占用无法覆盖）→
 *       {@code installer /quiet} → 再等 2 秒 → 重新拉起启动器；</li>
 *   <li>启动器退出；助手在新控制台窗口外静默执行；</li>
 *   <li>新版启动时看到 pending 且版本已到位 → 提示「已更新到 X」并清标记。</li>
 * </ol>
 */
public final class UpdateInstaller {

    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();

    private UpdateInstaller() {
    }

    /** 下载与安装用的目录：%LOCALAPPDATA%\\NekoCraftLauncher\\update（不可用则退回临时目录）。 */
    public static File updateDir() {
        String localAppData = System.getenv("LOCALAPPDATA");
        File base = localAppData == null || localAppData.isBlank()
                ? new File(System.getProperty("java.io.tmpdir"), "NekoCraftLauncher")
                : new File(localAppData, "NekoCraftLauncher");
        File dir = new File(base, "update");
        if (!dir.isDirectory() && !dir.mkdirs() && !dir.isDirectory()) {
            File fallback = new File(System.getProperty("java.io.tmpdir"), "NekoCraftLauncher-update");
            fallback.mkdirs();
            return fallback;
        }
        return dir;
    }

    /** pending 标记：记录「已经下好、等安装」的版本。 */
    public record Pending(String version, String installerPath, long at) {
    }

    public static File pendingFile() {
        return new File(updateDir(), "pending.json");
    }

    public static void writePending(String version, File installer) {
        try {
            Pending pending = new Pending(version, installer.getAbsolutePath(), System.currentTimeMillis());
            Files.writeString(pendingFile().toPath(), GSON.toJson(pending), StandardCharsets.UTF_8);
        } catch (IOException ignored) {
            // 标记写不进去不影响安装本身
        }
    }

    public static Pending readPending() {
        File file = pendingFile();
        if (!file.isFile()) {
            return null;
        }
        try {
            return GSON.fromJson(Files.readString(file.toPath(), StandardCharsets.UTF_8), Pending.class);
        } catch (Exception e) {
            return null;
        }
    }

    public static void clearPending() {
        try {
            Files.deleteIfExists(pendingFile().toPath());
        } catch (IOException ignored) {
            // 删不掉就算了，下次再删
        }
    }

    /** 当前运行的启动器 exe；jpackage 启动时由 jpackage.app-path 提供。 */
    public static File currentLauncherExe() {
        String appPath = System.getProperty("jpackage.app-path");
        if (appPath != null && !appPath.isBlank()) {
            File exe = new File(appPath);
            if (exe.isFile()) {
                return exe;
            }
        }
        // 免安装版（jar 直接跑）时没有 exe，就退回到 jar 所在目录
        try {
            return new File(UpdateInstaller.class.getProtectionDomain()
                    .getCodeSource().getLocation().toURI());
        } catch (Exception e) {
            return null;
        }
    }

    /**
     * 写安装助手并返回它的路径。调用方负责写完就退出启动器。
     *
     * @param installer 已下载的安装包（jpackage exe）
     * @param relaunchTo 安装完成后要重新拉起的启动器 exe（可为 null）
     */
    public static File prepareApplyScript(File installer, File relaunchTo) throws IOException {
        File dir = updateDir();
        File script = new File(dir, "apply-update.cmd");
        String relaunch = relaunchTo == null ? "" : relaunchTo.getAbsolutePath();
        StringBuilder body = new StringBuilder();
        body.append("@echo off\r\n");
        body.append("chcp 65001 >nul\r\n");
        body.append("rem generated by Neko Craft Launcher: wait for exit -> silent install -> relaunch\r\n");
        body.append("timeout /t 2 /nobreak >nul\r\n");
        body.append("start /wait \"\" \"").append(installer.getAbsolutePath()).append("\" /quiet\r\n");
        body.append("timeout /t 2 /nobreak >nul\r\n");
        if (!relaunch.isBlank()) {
            body.append("if exist \"").append(relaunch).append("\" start \"\" \"")
                    .append(relaunch).append("\"\r\n");
        }
        body.append("exit /b 0\r\n");
        Files.writeString(script.toPath(), body.toString(), StandardCharsets.UTF_8);
        return script;
    }

    /** 启动助手脚本（脱离当前进程，窗口隐藏）。 */
    public static void runDetached(File script) throws IOException {
        ProcessBuilder builder = new ProcessBuilder("cmd.exe", "/c", script.getAbsolutePath());
        builder.directory(script.getParentFile());
        builder.redirectErrorStream(true);
        builder.redirectOutput(ProcessBuilder.Redirect.DISCARD);
        builder.start();
    }

    /**
     * 免安装版（zip 解压出来的目录）就地更新：把新 zip 解压到临时目录，覆盖 app / runtime / exe。
     *
     * <p>{@code game\\} 与 {@code config.json} 不在 zip 里，所以存档和配置不会被碰。
     */
    public static File preparePortableScript(File zip, File root, File relaunch) throws IOException {
        File dir = updateDir();
        File script = new File(dir, "apply-update.ps1");
        File staging = new File(dir, "staging");
        File backup = new File(backupRoot(), "app-" + stamp());
        String rows = String.join("\r\n", new String[] {
            "$ErrorActionPreference = 'Stop'",
            "# generated by Neko Craft Launcher: wait -> backup -> expand -> overwrite -> relaunch",
            "Start-Sleep -Seconds 2",
            "$root = '" + escape(root.getAbsolutePath()) + "'",
            "$backup = '" + escape(backup.getAbsolutePath()) + "'",
            "$staging = '" + escape(staging.getAbsolutePath()) + "'",
            "$log = '" + escape(new File(dir, "update-error.log").getAbsolutePath()) + "'",
            "function Save-Old {",
            "  New-Item -ItemType Directory -Path $backup -Force | Out-Null",
            "  foreach ($name in @('app','runtime','NekoCraftLauncher.exe')) {",
            "    $src = Join-Path $root $name",
            "    if (Test-Path $src) {",
            "      if ((Get-Item $src).PSIsContainer) {",
            "        $dst = Join-Path $backup $name",
            "        New-Item -ItemType Directory -Path $dst -Force | Out-Null",
            "        Copy-Item (Join-Path $src '*') $dst -Recurse -Force",
            "      } else { Copy-Item $src $dst -Force }",
            "    }",
            "  }",
            "}",
            "function Restore-Old {",
            "  if (-not (Test-Path $backup)) { return }",
            "  foreach ($name in @('app','runtime','NekoCraftLauncher.exe')) {",
            "    $src = Join-Path $backup $name",
            "    $dst = Join-Path $root $name",
            "    if ((Test-Path $src) -and (Get-Item $src).PSIsContainer) {",
            "      New-Item -ItemType Directory -Path $dst -Force | Out-Null",
            "      Copy-Item (Join-Path $src '*') $dst -Recurse -Force",
            "    } elseif (Test-Path $src) { Copy-Item $src $dst -Force }",
            "  }",
            "}",
            "try {",
            "  Save-Old",
            "  if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }",
            "  Expand-Archive -LiteralPath '" + escape(zip.getAbsolutePath()) + "' -DestinationPath $staging -Force",
            "  Copy-Item -Path (Join-Path $staging '*') -Destination $root -Recurse -Force",
            "} catch {",
            "  Add-Content -Path $log -Value ((Get-Date).ToString('s') + ' apply failed: ' + $_.Exception.Message)",
            "  try { Restore-Old } catch { }",
            "}",
            "if (Test-Path '" + escape(root.getAbsolutePath()) + "\\" + rootExeName(root) + "') {",
            "  try { Start-Process -FilePath '" + escape(relaunch == null
                ? new File(root, rootExeName(root)).getAbsolutePath()
                : relaunch.getAbsolutePath()) + "' } catch { }",
            "}"
        });
        Files.writeString(script.toPath(), rows + "\r\n", StandardCharsets.UTF_8);
        return script;
    }

    /** 回滚：把最近一次备份换回去。 */
    public static File prepareRollbackScript(File backup, File root) throws IOException {
        File script = new File(updateDir(), "rollback.ps1");
        String rows = String.join("\r\n", new String[] {
            "$ErrorActionPreference = 'Stop'",
            "# generated by Neko Craft Launcher: restore the previous build",
            "Start-Sleep -Seconds 2",
            "$root = '" + escape(root.getAbsolutePath()) + "'",
            "$backup = '" + escape(backup.getAbsolutePath()) + "'",
            "foreach ($name in @('app','runtime','NekoCraftLauncher.exe')) {",
            "  $src = Join-Path $backup $name",
            "  $dst = Join-Path $root $name",
            "  if ((Test-Path $src) -and (Get-Item $src).PSIsContainer) {",
            "    New-Item -ItemType Directory -Path $dst -Force | Out-Null",
            "    Copy-Item (Join-Path $src '*') $dst -Recurse -Force",
            "  } elseif (Test-Path $src) { Copy-Item $src $dst -Force }",
            "}",
            "if (Test-Path '" + escape(new File(root, rootExeName(root)).getAbsolutePath()) + "') {",
            "  try { Start-Process -FilePath '" + escape(new File(root, rootExeName(root)).getAbsolutePath()) + "' } catch { }",
            "}"
        });
        Files.writeString(script.toPath(), rows + "\r\n", StandardCharsets.UTF_8);
        return script;
    }

    /** 备份根目录：%LOCALAPPDATA%\\NekoCraftLauncher\\update\\backup。 */
    public static File backupRoot() {
        File dir = new File(updateDir(), "backup");
        dir.mkdirs();
        return dir;
    }

    /** 最近一次备份（没有则返回 null）。 */
    public static File latestBackup() {
        File[] dirs = backupRoot().listFiles(File::isDirectory);
        if (dirs == null || dirs.length == 0) {
            return null;
        }
        File newest = dirs[0];
        for (File dir : dirs) {
            if (dir.lastModified() > newest.lastModified()) {
                newest = dir;
            }
        }
        return newest;
    }

    private static String stamp() {
        return java.time.LocalDateTime.now()
                .format(java.time.format.DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss"));
    }
    /** 免安装目录里的启动器 exe 名字。 */
    private static String rootExeName(File root) {
        File direct = new File(root, "NekoCraftLauncher.exe");
        return direct.getName();
    }

    /** PowerShell 单引号字符串转义。 */
    private static String escape(String path) {
        return path.replace("'", "''");
    }

    /** 当前运行位置属于「安装版」还是「免安装版」。 */
    public static boolean isInstalledLayout(File launcher) {
        if (launcher == null) {
            return false;
        }
        String path = launcher.getAbsolutePath().toLowerCase(java.util.Locale.ROOT);
        String localAppData = System.getenv("LOCALAPPDATA");
        if (localAppData != null && !localAppData.isBlank()) {
            String installedRoot = new File(localAppData, "NekoCraftLauncher")
                    .getAbsolutePath().toLowerCase(java.util.Locale.ROOT);
            if (path.startsWith(installedRoot)) {
                return true;
            }
        }
        return path.contains("\\program files");
    }

    /** 免安装版的根目录：启动器 exe 所在目录（jar 直接跑时是 jar 所在目录的上一级）。 */
    public static File portableRoot(File launcher) {
        if (launcher == null) {
            return null;
        }
        File parent = launcher.getParentFile();
        if (parent != null && new File(parent, "NekoCraftLauncher.exe").isFile()) {
            return parent;
        }
        return parent == null ? null : parent.getParentFile();
    }

    /** 跑 PowerShell 助手脚本（隐藏窗口）。 */
    public static void runPowerShellDetached(File script) throws IOException {
        ProcessBuilder builder = new ProcessBuilder("powershell.exe", "-NoProfile",
                "-ExecutionPolicy", "Bypass", "-WindowStyle", "Hidden", "-File",
                script.getAbsolutePath());
        builder.directory(script.getParentFile());
        builder.redirectErrorStream(true);
        builder.redirectOutput(ProcessBuilder.Redirect.DISCARD);
        builder.start();
    }
    /**
     * 把安装包复制到稳定的更新目录（临时目录可能被清理），返回复制后的文件。
     * 复制失败就返回原文件，不阻断流程。
     */
    public static File stashInstaller(File downloaded, String version) {
        try {
            String safe = version.replaceAll("[^0-9A-Za-z._-]", "_");
            File target = new File(updateDir(), "NekoCraftLauncher-Setup-" + safe + ".exe");
            Files.copy(downloaded.toPath(), target.toPath(), StandardCopyOption.REPLACE_EXISTING);
            return target;
        } catch (Exception e) {
            return downloaded;
        }
    }
}
